#!/usr/bin/env python3
r"""
Generate the perplexity-dissociation table for section 4 (tab:ppl).

One compact table carrying all three claims of the perplexity analysis:
rows pair each method's WikiText and FinMix configurations so the reader
sees (a) PPL barely moves under moderate compression while tasks fall,
(b) PPL magnifies under sparsity but cannot localize damage, and (c) within
each method the higher-PPL corpus is the better downstream model.

Output: paper/tables/ppl_table.tex
"""

import glob
import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paper_metrics import load_scores as _shared_load_scores
import re

MODEL = "Llama-3.1-8B-Instruct"
PPL_JSON = "experiments/results/analysis/perplexity_Llama-3.1-8B-Instruct.json"
FIN_PPL_JSON = "experiments/results/analysis/fin_perplexity_Llama-3.1-8B-Instruct.json"
ROWS = [
    ("BF16", "--", "bf16"),
    ("RTN", "--", "rtn_w4a16"),
    ("GPTQ", "\\wiki{}", "gptq_w4a16_c1"),
    ("", "\\finmix{}", "gptq_w4a16_c3"),
    ("AWQ", "\\wiki{}", "awq_w4a16_asym_c1"),
    ("", "\\finmix{}", "awq_w4a16_asym_c3"),
    ("SmoothQuant", "\\wiki{}", "smoothquant_w8a8_c1"),
    ("", "\\finmix{}", "smoothquant_w8a8_c3"),
    ("SparseGPT", "\\wiki{}", "sparsegpt_unstructured_c1"),
    ("", "\\finmix{}", "sparsegpt_unstructured_c3full"),
    ("Wanda", "\\wiki{}", "wanda_4of8_c1"),
    ("", "\\finmix{}", "wanda_4of8_c3full"),
]
TASK_COLS = [(5, "FinQA"), (9, "ConvFinQA")]


def load_task_scores():
    return _shared_load_scores(MODEL)


def main():
    ppl = json.load(open(PPL_JSON))
    fppl = json.load(open(FIN_PPL_JSON))
    scores = load_task_scores()
    base_ppl = ppl["bf16"]

    lines = [
        "% AUTO-GENERATED by scripts/analysis/generate_ppl_table_tex.py",
        "\\begin{table}[t]",
        "\\caption{Perplexity on WikiText test and on held-out financial text"
        " (earnings-call transcripts used in no calibration corpus or"
        " evaluation set), alongside judge accuracy on the two multi-step"
        " numerical-reasoning tasks, FinQA and ConvFinQA (Llama-3.1-8B)."
        " Rows pair"
        " each method's \\textsc{WikiText}- and \\textsc{FinMix}-calibrated"
        " configurations.}",
        "\\label{tab:ppl}",
        "\\centering\\small",
        "\\begin{tabular}{llrrrr}",
        "\\toprule",
        "Method & Calib. & WikiPPL$\\downarrow$ & FinPPL$\\downarrow$ & FinQA$\\uparrow$ & ConvFinQA$\\uparrow$ \\\\",
        "\\midrule",
    ]
    for lbl, calib, cfg in ROWS:
        p = ppl.get(cfg)
        fp = fppl.get(cfg)
        cells = [f"{p:.2f}" if p else "--", f"{fp:.2f}" if fp else "--"]
        for t, _name in TASK_COLS:
            v = scores.get((cfg, t))
            cells.append(f"{v:.1f}" if v is not None else "--")
        lines.append(f"{lbl} & {calib} & " + " & ".join(cells) + " \\\\")
        if cfg in ("rtn_w4a16", "gptq_w4a16_c3", "awq_w4a16_asym_c3", "smoothquant_w8a8_c3", "sparsegpt_unstructured_c3full"):
            lines.append("\\addlinespace")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    os.makedirs("paper/tables", exist_ok=True)
    with open("paper/tables/ppl_table.tex", "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote paper/tables/ppl_table.tex")


if __name__ == "__main__":
    main()
