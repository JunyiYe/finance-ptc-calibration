#!/usr/bin/env python3
"""
Generate the error-attribution table (tab:attr) from the current
error_attribution_*.json files, replacing the previously hand-built
paper/tables/attribution_table.tex (whose SparseGPT column had gone stale
after the 2026-07-29 pruning budget-fix re-run).

Settings shown: GPTQ/FinQA and SparseGPT/ConvFinQA (fixed vs seeded
control). The full 2x2 grid lives in error_attribution_grid.md and is
released with the code.
"""

import json
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

MODEL = "Llama-3.1-8B-Instruct"
A = "experiments/results/analysis"
CATS = [("reasoning", "reasoning"), ("unit_scale", "unit/scale"),
        ("arithmetic", "arithmetic"), ("extraction", "extraction"),
        ("format", "format"), ("other", "other")]
SETTINGS = [("GPTQ / FinQA", "gptq_w4a16", 5),
            ("SparseGPT / ConvFinQA", "sparsegpt_unstructured", 9)]


def load(name, tnum, subset):
    suffix = "" if subset == "fixed" else "_unfixed"
    path = f"{A}/error_attribution_{name}_c1toc3{suffix}_{MODEL}_t{tnum}.json"
    ps = json.load(open(path))["per_sample"]
    if isinstance(ps, list):
        cats = [s["category"] for s in ps if s.get("category")]
    else:
        cats = [(v["category"] if isinstance(v, dict) else v)
                for v in ps.values()
                if (v.get("category") if isinstance(v, dict) else v)]
    return cats


def main():
    cols = []
    for _label, name, tnum in SETTINGS:
        for subset in ("fixed", "unfixed"):
            cats = load(name, tnum, subset)
            n = len(cats)
            cols.append((n, {k: sum(1 for c in cats if c == k) / n * 100
                             for k, _ in CATS}))

    lines = [
        "% AUTO-GENERATED by scripts/analysis/generate_attribution_table_tex.py"
        " -- do not edit by hand",
        "\\begin{table}[t]",
        "\\caption{Judge-attributed primary error type of the \\wiki-calibrated"
        " model's mistakes, split into those the \\finmix{} model fixes and a"
        " seeded control of those it does not (\\%). Two settings: quantization"
        " (GPTQ, FinQA) and pruning (SparseGPT, ConvFinQA). Samples the judge"
        " could not attribute are excluded from $n$; the remaining"
        " method--task combinations are released with the code.}",
        "\\label{tab:attr}",
        "\\centering\\small",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "& \\multicolumn{2}{c}{GPTQ / FinQA} &"
        " \\multicolumn{2}{c}{SparseGPT / ConvFinQA} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        "Error type & fixed & control & fixed & control \\\\",
        "\\midrule",
    ]
    for key, label in CATS:
        cells = " & ".join(f"{c[1][key]:.1f}" for c in cols)
        lines.append(f"{label:11s} & {cells} \\\\")
    lines.append("\\midrule")
    lines.append("$n$ & " + " & ".join(str(c[0]) for c in cols) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    out = "paper/tables/attribution_table.tex"
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
