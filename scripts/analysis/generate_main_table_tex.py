#!/usr/bin/env python3
r"""
Generate the damage table (Table tab:main): every method under the standard
WikiText recipe vs BF16. Family labels (Quantization / Pruning) are rotated
vertically in the first column via \multirow + \rotatebox to save space.

Output: paper/tables/main_table.tex  (\input from main.tex)
"""

import argparse
import csv
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paper_metrics import load_scores as _shared_load_scores

MODEL = "Llama-3.1-8B-Instruct"

ap = argparse.ArgumentParser()
ap.add_argument("--calib", default="c1", choices=["c1", "c2"],
                help="c2 writes the C4-calibrated replication table "
                     "(main_table_c4.tex, label tab:main_c4)")
CALIB = ap.parse_args().calib

def load_damage_sig():
    out = {}
    path = ("experiments/results/analysis/damage_significance_" + MODEL
            + ("" if CALIB == "c1" else "_" + CALIB) + ".csv")
    if os.path.exists(path):
        for row in csv.DictReader(open(path)):
            out[(row["method"], int(row["task"][1:]))] = row["sig"]
    return out

TASKS = [1, 2, 3, 6, 8, 10, 4, 5, 9, 11]
HEAD = ["FPB", "FOMC", "Headlines", "FinRED", "FinCausal", "BigData22",
        "CFA", "FinQA", "ConvFinQA", "TAT-QA"]
FAMILIES = [  # (rotated label, [(row label, cfg prefix)])
    (None, [("BF16", "bf16")]),
    ("Quantization", [("RTN", "rtn_w4a16"),
                      ("GPTQ", f"gptq_w4a16_{CALIB}"),
                      ("AWQ", f"awq_w4a16_asym_{CALIB}"),
                      ("SmoothQuant", f"smoothquant_w8a8_{CALIB}")]),
    ("Pruning", [("SparseGPT", f"sparsegpt_unstructured_{CALIB}"),
                 ("Wanda", f"wanda_4of8_{CALIB}")]),
]


def load_ppl():
    import json
    p = "experiments/results/analysis/perplexity_Llama-3.1-8B-Instruct.json"
    return json.load(open(p)) if os.path.exists(p) else {}


def main():
    r = _shared_load_scores(MODEL)
    ppl = load_ppl()
    dsig = load_damage_sig()
    NAME2SIG = {"RTN": "RTN", "GPTQ": "GPTQ", "AWQ": "AWQ",
                "SmoothQuant": "SmoothQuant", "SparseGPT": "SparseGPT",
                "Wanda": "Wanda"}
    ncol = len(TASKS) + 3  # family + method + ppl + tasks
    if CALIB == "c1":
        caption = (
            "\\caption{Degradation under the standard recipe: Llama-3.1-8B"
            " compressed with \\textsc{WikiText} calibration (RTN is"
            " calibration-free). FPB, FOMC, Headlines, FinRED,"
            " and BigData22 report weighted F1 (\\%); FinCausal reports macro-F1"
            " (\\%); CFA, FinQA,"
            " ConvFinQA, and TAT-QA report accuracy (\\%), with FinQA, ConvFinQA,"
            " and TAT-QA scored by an LLM judge (identical across configurations)."
            " PPL = WikiText test perplexity (2048-token windows). Avg.\\ is"
            " the unweighted mean of the displayed scores in each block,"
            " with its difference from the BF16 mean in parentheses; the"
            " classification mean excludes BigData22, which stays near its"
            " random baseline for every configuration."
            " Stars mark"
            " the significance of each score's difference from BF16 under the"
            " paired tests of Section~\\ref{sec:protocol}"
            " ($^{*}p{<}.05$, $^{**}p{<}.01$, $^{***}p{<}.001$)."
            " Stars are uncorrected per-test significance; counts quoted in"
            " the text apply a Benjamini--Hochberg correction, and adjusted"
            " $q$-values for every test are released with the code.}")
        label, banner = "tab:main", "\\wiki{}"
        outfile = "paper/tables/main_table.tex"
    else:
        caption = (
            "\\caption{Replication of Table~\\ref{tab:main} with \\web{}"
            " calibration; the BF16 and RTN rows are repeated unchanged"
            " (neither consumes calibration data). Metrics, test sets, judge,"
            " and significance tests are identical to Table~\\ref{tab:main}.}")
        label, banner = "tab:main_c4", "\\web{}"
        outfile = "paper/tables/main_table_c4.tex"
    lines = [
        "% AUTO-GENERATED by scripts/analysis/generate_main_table_tex.py -- do not edit by hand",
        "\\begin{table*}[t]",
        caption,
        f"\\label{{{label}}}",
        "\\centering\\small",
        "\\setlength{\\tabcolsep}{1pt}",
        "\\begin{tabular}{llc" + "c" * 6 + "c" + "c" * 4 + "c}",
        "\\toprule",
        f"\\multicolumn{{3}}{{l}}{{Calibration: {banner}}} &"
        " \\multicolumn{7}{c}{Classification} & \\multicolumn{5}{c}{Numerical QA} \\\\",
        "\\cmidrule(lr){4-10}\\cmidrule(lr){11-15}",
        " & Method & PPL$\\downarrow$ & "
        + " & ".join(f"{h}$\\uparrow$" for h in HEAD[:6])
        + " & \\emph{Avg.}$\\uparrow$ & "
        + " & ".join(f"{h}$\\uparrow$" for h in HEAD[6:])
        + " & \\emph{Avg.}$\\uparrow$ \\\\",
        "\\midrule",
    ]
    def raw_avg(vv):
        have = [x for x in vv if x is not None]
        return round(sum(have) / len(have), 1) if have else None

    # classification Avg excludes BigData22 (near-random for every
    # configuration; its swings dominate a 6-task mean) — index 5 of TASKS
    bf16_vals = [round(r[("bf16", t)], 1) for t in TASKS]
    bf16_avg = {"cls": raw_avg(bf16_vals[:5]), "qa": raw_avg(bf16_vals[6:])}

    for fi, (family, rows_) in enumerate(FAMILIES):
        for ri, (lbl, cfg) in enumerate(rows_):
            cells, vals = [], []
            for t in TASKS:
                v = r.get((cfg, t))
                if v is None:
                    cells.append("--")
                    vals.append(None)
                    continue
                sig = dsig.get((NAME2SIG.get(lbl, ""), t), "")
                star = f"$^{{{sig}}}$" if sig else ""
                cells.append(f"{v:.1f}{star}")
                vals.append(round(v, 1))

            def block_avg(vv, block):
                a = raw_avg(vv)
                if a is None:
                    return "--"
                if cfg == "bf16":
                    return f"\\emph{{{a:.1f}}}"
                d = round(a - bf16_avg[block], 1)
                return f"\\emph{{{a:.1f} (${d:+.1f}$)}}"

            cells = (cells[:6] + [block_avg(vals[:5], "cls")]
                     + cells[6:] + [block_avg(vals[6:], "qa")])
            pv = ppl.get(cfg)
            pcell = f"{pv:.2f}" if pv else "--"
            fam = (f"\\multirow{{{len(rows_)}}}{{*}}{{{family}}}"
                   if family and ri == 0 else "")
            lines.append(f"{fam} & {lbl} & {pcell} & " + " & ".join(cells) + " \\\\")
        lines.append("\\midrule" if fi < len(FAMILIES) - 1 else "\\bottomrule")
    lines += ["\\end{tabular}", "\\end{table*}"]

    with open(outfile, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {outfile}")


if __name__ == "__main__":
    main()
