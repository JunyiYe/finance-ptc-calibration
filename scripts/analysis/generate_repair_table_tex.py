#!/usr/bin/env python3
"""
Generate the repair table (Section 5): one FinMix-calibrated row per method,
each cell showing "absolute score (delta vs WikiText, significance stars)".

Deltas and stars come from calibration_significance_*.csv (treat=c3, base=c1),
absolute scores from paper_metrics.load_scores. Output: paper/tables/repair_table.tex
"""

import csv
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paper_metrics import load_scores

MODEL = "Llama-3.1-8B-Instruct"
TASKS = [1, 2, 3, 6, 8, 10, 4, 5, 9, 11]
HEAD = ["FPB", "FOMC", "Headlines", "FinRED", "FinCausal", "BigData22",
        "CFA", "FinQA", "ConvFinQA", "TAT-QA"]
ROWS = [  # (label, finmix cfg, wikitext cfg, sig-csv method key)
    ("GPTQ", "gptq_w4a16_c3", "gptq_w4a16_c1", "gptq_w4a16"),
    ("AWQ", "awq_w4a16_asym_c3", "awq_w4a16_asym_c1", "awq_w4a16_asym"),
    ("SmoothQuant", "smoothquant_w8a8_c3", "smoothquant_w8a8_c1", "smoothquant_w8a8"),
    ("SparseGPT", "sparsegpt_unstructured_c3full", "sparsegpt_unstructured_c1", "sparsegpt_unstructured"),
    ("Wanda", "wanda_4of8_c3full", "wanda_4of8_c1", "wanda_4of8"),
]
SIG_CSV = f"experiments/results/analysis/calibration_significance_{MODEL}.csv"


def load_contrasts():
    out = {}
    with open(SIG_CSV) as f:
        for row in csv.DictReader(f):
            if row["treat"] == "c3" and row["base"] == "c1":
                t = int(row["task"][1:])
                out[(row["method"], t)] = row["sig"]
    return out


def main():
    scores = load_scores(MODEL)
    contrasts = load_contrasts()
    lines = [
        "% AUTO-GENERATED by scripts/analysis/generate_repair_table_tex.py -- do not edit by hand",
        "\\begin{table*}[t]",
        "\\caption{Repair from domain-matched calibration: Llama-3.1-8B"
        " compressed with \\textsc{FinMix} calibration in place of"
        " \\textsc{WikiText}, at an identical token budget. Each cell shows"
        " the \\textsc{FinMix} score with, in parentheses, its difference"
        " from the corresponding \\textsc{WikiText} configuration of"
        " Table~\\ref{tab:main}. Metrics as in Table~\\ref{tab:main}."
        " Significance of each difference is from exact two-sided McNemar"
        " tests (accuracy tasks) or paired bootstrap (F1 tasks):"
        " $^{*}p{<}.05$, $^{**}p{<}.01$, $^{***}p{<}.001$; exact $p$-values"
        " are released with the code.}",
        "\\label{tab:repair}",
        "\\centering\\footnotesize",
        "\\setlength{\\tabcolsep}{3.5pt}",
        "\\begin{tabular}{l" + "c" * len(TASKS) + "}",
        "\\toprule",
        " & \\multicolumn{6}{c}{Classification} & \\multicolumn{4}{c}{Numerical QA} \\\\",
        "\\cmidrule(lr){2-7}\\cmidrule(lr){8-11}",
        "Method & " + " & ".join(HEAD) + " \\\\",
        "\\midrule",
    ]
    for label, cfg, base_cfg, mkey in ROWS:
        cells = []
        for t in TASKS:
            v = scores.get((cfg, t))
            b = scores.get((base_cfg, t))
            sig = contrasts.get((mkey, t))
            if v is None or b is None or sig is None:
                cells.append("--")
                continue
            # display delta from the ROUNDED absolutes so it is consistent
            # with Table tab:main; stars come from the exact per-sample test
            d = round(v, 1) - round(b, 1)
            stars = f"^{{{sig}}}" if sig else ""
            cells.append(f"{v:.1f} (${'+' if d >= 0 else '-'}{abs(d):.1f}{stars}$)")
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    out = "paper/tables/repair_table.tex"
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
