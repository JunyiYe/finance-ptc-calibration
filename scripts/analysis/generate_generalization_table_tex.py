#!/usr/bin/env python3
"""
Generate the generalization table (Section 6): Panel A = Qwen3-8B (second
model family), Panel B = Llama-3.1-70B (scale). Same ten task columns as the
main tables; WikiText/FinMix rows per method; dashes for runs still pending.

Output: paper/tables/generalization_table.tex  (label tab:gen)
"""

import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from paper_metrics import load_scores

TASKS = [1, 2, 3, 6, 8, 10, 4, 5, 9, 11]
HEAD = ["FPB", "FOMC", "Headlines", "FinRED", "FinCausal", "BigData22",
        "CFA", "FinQA", "ConvFinQA", "TAT-QA"]

PANELS = [
    ("Qwen3-8B", "Qwen3-8B", [
        ("BF16", "--", "bf16"),
        ("RTN", "--", "rtn_w4a16"),
        ("GPTQ", "\\wiki{}", "gptq_w4a16_c1"),
        ("", "\\finmix{}", "gptq_w4a16_c3full"),
        ("AWQ", "\\wiki{}", "awq_w4a16_asym_c1"),
        ("", "\\finmix{}", "awq_w4a16_asym_c3full"),
        ("SmoothQuant", "\\wiki{}", "smoothquant_w8a8_c1"),
        ("", "\\finmix{}", "smoothquant_w8a8_c3full"),
        ("SparseGPT", "\\wiki{}", "sparsegpt_unstructured_c1"),
        ("", "\\finmix{}", "sparsegpt_unstructured_c3full"),
        ("Wanda", "\\wiki{}", "wanda_4of8_c1"),
        ("", "\\finmix{}", "wanda_4of8_c3full"),
    ]),
    ("Llama-3.1-70B", "Llama-3.1-70B-Instruct", [
        ("BF16", "--", "bf16"),
        ("RTN", "--", "rtn_w4a16"),
        ("GPTQ", "\\wiki{}", "gptq_w4a16_c1"),
        ("", "\\finmix{}", "gptq_w4a16_c3"),
        ("AWQ", "\\wiki{}", "awq_w4a16_asym_c1"),
        ("", "\\finmix{}", "awq_w4a16_asym_c3"),
        ("SmoothQuant", "\\wiki{}", "smoothquant_w8a8_c1"),
        ("", "\\finmix{}", "smoothquant_w8a8_c3full"),
        ("SparseGPT", "\\wiki{}", "sparsegpt_unstructured_c1"),
        ("", "\\finmix{}", "sparsegpt_unstructured_c3full"),
        ("Wanda", "\\wiki{}", "wanda_4of8_c1"),
        ("", "\\finmix{}", "wanda_4of8_c3full"),
    ]),
]


def main():
    lines = [
        "% AUTO-GENERATED by scripts/analysis/generate_generalization_table_tex.py -- do not edit by hand",
        "\\begin{table*}[t]",
        "\\caption{Generalization of the damage--recovery relationship across"
        " model family (Qwen3-8B) and scale (Llama-3.1-70B); metrics as in"
        " Table~\\ref{tab:main}. Under quantization both models are nearly"
        " undamaged and the calibration contrast is null; where damage"
        " appears (sparsity at 8B, calibration-free RTN at 70B), the"
        " \\textsc{FinMix} repair re-emerges. Dashes mark runs still in"
        " progress.}",
        "\\label{tab:gen}",
        "\\centering\\small",
        "\\begin{tabular}{ll" + "c" * len(TASKS) + "}",
        "\\toprule",
        " & & \\multicolumn{6}{c}{Classification} & \\multicolumn{4}{c}{Numerical QA} \\\\",
        "\\cmidrule(lr){3-8}\\cmidrule(lr){9-12}",
        "Method & Calib. & " + " & ".join(HEAD) + " \\\\",
    ]
    for pi, (pname, model, rows_) in enumerate(PANELS):
        r = load_scores(model)
        lines.append("\\midrule")
        lines.append(f"\\multicolumn{{{len(TASKS)+2}}}{{l}}{{\\textbf{{{pname}}}}} \\\\")
        for lbl, calib, cfg in rows_:
            cells = []
            for t in TASKS:
                v = r.get((cfg, t))
                cells.append(f"{v:.1f}" if v is not None else "--")
            if all(c == "--" for c in cells):
                continue
            lines.append(f"{lbl} & {calib} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    out = "paper/tables/generalization_table.tex"
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
